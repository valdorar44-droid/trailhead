import { createHash } from 'node:crypto';
import { existsSync, readdirSync } from 'node:fs';
import { delimiter, join } from 'node:path';

const BLOCKED_ACTION_COPY = [
  /\b(buy|purchase|subscribe|checkout|book now|reserve|pay|payout)\b/i,
  /\b(delete|remove account|sign out|log out|reset|clear data)\b/i,
  /\b(submit|send report|publish|post report|claim prize|redeem|refer now|discard|end tour|stop tour)\b/i,
  /\b(download|save|unsave|favorite|follow|join|acquire|get free|restore|start tour|start trip|start navigation)\b/i,
  /\b(cash\s?app|paypal|bank deposit)\b/i,
];

const SUSPICIOUS_COPY = [
  { code: 'raw_slug', pattern: /\b[a-z]+_[a-z][a-z_]+\b/ },
  { code: 'developer_copy', pattern: /\b(endpoint|database|payload|debug|internal slug|undefined|null)\b/i },
  { code: 'provider_copy', pattern: /\b(mapbox|geoapify|nominatim|openai|anthropic)\b/i },
  { code: 'unsupported_assurance', pattern: /\b(always safe|guaranteed safe|real[- ]?time|live alerts?|you(?:'ve| have) driven these roads)\b/i },
  { code: 'ai_badge_or_copy', pattern: /\b(ai[- ]powered|artificial intelligence|generated by ai|ai assistant)\b/i },
  { code: 'accessibility_icon_glyph', pattern: /[\uE000-\uF8FF]|(?:ï|ð)[\u0080-\uFFFF]{1,3}/ },
];

export function parseArgs(argv) {
  const result = {
    command: 'capture',
    serials: [],
    packageName: 'com.trailhead.app',
    label: 'baseline',
    output: null,
    adb: null,
    scenario: null,
    executeSafeActions: false,
    allowTextActions: false,
    recordSeconds: 0,
    logLines: 2000,
  };
  const args = [...argv];
  if (args[0] && !args[0].startsWith('-')) result.command = args.shift();
  while (args.length) {
    const flag = args.shift();
    const take = () => {
      const value = args.shift();
      if (!value || value.startsWith('--')) throw new Error(`${flag} requires a value`);
      return value;
    };
    if (flag === '--serial') result.serials.push(take());
    else if (flag === '--package') result.packageName = take();
    else if (flag === '--label') result.label = take();
    else if (flag === '--output') result.output = take();
    else if (flag === '--adb') result.adb = take();
    else if (flag === '--scenario') result.scenario = take();
    else if (flag === '--record-seconds') result.recordSeconds = Number(take());
    else if (flag === '--log-lines') result.logLines = Number(take());
    else if (flag === '--execute-safe-actions') result.executeSafeActions = true;
    else if (flag === '--allow-text-actions') result.allowTextActions = true;
    else if (flag === '--help' || flag === '-h') result.command = 'help';
    else throw new Error(`Unknown option: ${flag}`);
  }
  if (!Number.isInteger(result.recordSeconds) || result.recordSeconds < 0 || result.recordSeconds > 30) {
    throw new Error('--record-seconds must be an integer from 0 to 30');
  }
  if (!Number.isInteger(result.logLines) || result.logLines < 100 || result.logLines > 10000) {
    throw new Error('--log-lines must be an integer from 100 to 10000');
  }
  if (result.command === 'scenario' && !result.scenario) throw new Error('scenario requires --scenario <file.json>');
  return result;
}

function executableNames() {
  return process.platform === 'win32' ? ['adb.exe', 'adb'] : ['adb', 'adb.exe'];
}

function pathCandidates() {
  const candidates = [];
  // In WSL, the Windows adb server owns USB and Windows-emulator transports.
  // Prefer that platform-tools binary before a separate Linux adb daemon.
  if (process.platform !== 'win32' && existsSync('/mnt/c/Users')) {
    for (const user of readdirSync('/mnt/c/Users', { withFileTypes: true }).filter((entry) => entry.isDirectory())) {
      candidates.push(join('/mnt/c/Users', user.name, 'AppData', 'Local', 'Android', 'Sdk', 'platform-tools', 'adb.exe'));
    }
  }
  for (const name of executableNames()) {
    for (const dir of String(process.env.PATH || '').split(delimiter)) {
      if (dir) candidates.push(join(dir, name));
    }
  }
  for (const root of [process.env.ANDROID_HOME, process.env.ANDROID_SDK_ROOT]) {
    if (root) candidates.push(join(root, 'platform-tools', process.platform === 'win32' ? 'adb.exe' : 'adb'));
  }
  if (process.env.LOCALAPPDATA) {
    candidates.push(join(process.env.LOCALAPPDATA, 'Android', 'Sdk', 'platform-tools', 'adb.exe'));
  }
  if (process.env.HOME) {
    candidates.push(join(process.env.HOME, 'Android', 'Sdk', 'platform-tools', 'adb'));
    candidates.push(join(process.env.HOME, 'android-sdk', 'platform-tools', 'adb'));
  }
  return [...new Set(candidates)];
}

export function findAdb(explicitPath) {
  if (explicitPath) {
    if (!existsSync(explicitPath)) throw new Error(`adb not found at ${explicitPath}`);
    return explicitPath;
  }
  const found = pathCandidates().find((candidate) => existsSync(candidate));
  if (!found) throw new Error('adb was not found. Pass --adb <path> or set ANDROID_HOME.');
  return found;
}

export function parseDevices(output) {
  return String(output)
    .split(/\r?\n/)
    .slice(1)
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      const [serial, state, ...details] = line.split(/\s+/);
      const attributes = Object.fromEntries(details.filter((item) => item.includes(':')).map((item) => item.split(/:(.*)/s).slice(0, 2)));
      return { serial, state, attributes, raw: line };
    });
}

function decodeXml(value) {
  return String(value)
    .replaceAll('&quot;', '"')
    .replaceAll('&apos;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&amp;', '&');
}

export function parseUiNodes(xml) {
  const nodes = [];
  for (const match of String(xml).matchAll(/<node\s+([^>]*?)(?:\/>|>)/g)) {
    const attrs = {};
    for (const attr of match[1].matchAll(/([\w-]+)="([^"]*)"/g)) attrs[attr[1]] = decodeXml(attr[2]);
    const boundsMatch = attrs.bounds?.match(/^\[(\d+),(\d+)]\[(\d+),(\d+)]$/);
    nodes.push({
      ...attrs,
      bounds: boundsMatch
        ? { left: Number(boundsMatch[1]), top: Number(boundsMatch[2]), right: Number(boundsMatch[3]), bottom: Number(boundsMatch[4]) }
        : null,
    });
  }
  return nodes;
}

export function summarizeUi(nodes) {
  const unique = (values) => [...new Set(values.filter(Boolean))];
  const texts = unique(nodes.flatMap((node) => [node.text, node['content-desc']]));
  const resourceIds = unique(nodes.map((node) => node['resource-id']));
  const suspiciousCopy = [];
  for (const text of texts) {
    for (const rule of SUSPICIOUS_COPY) {
      if (rule.pattern.test(text)) suspiciousCopy.push({ code: rule.code, text });
    }
  }
  return {
    nodeCount: nodes.length,
    clickableCount: nodes.filter((node) => node.clickable === 'true').length,
    enabledClickableCount: nodes.filter((node) => node.clickable === 'true' && node.enabled !== 'false').length,
    visibleText: texts,
    resourceIds,
    likelyTestIds: resourceIds.filter((id) => id
      && !/^android:|^com\.android\./.test(id)
      && !/(?:^|\/)(?:action_bar_root|content|navigationBarBackground|statusBarBackground)$/.test(id)),
    suspiciousCopy,
  };
}

export function findNode(nodes, selector, packageName, allowTextActions = false) {
  if (!selector || typeof selector !== 'object') throw new Error('tap action requires a selector');
  let matches = [];
  if (selector.testID) {
    const expected = new Set([
      selector.testID,
      `${packageName}:id/${selector.testID}`,
      `${packageName}:id/${String(selector.testID).replaceAll('-', '_')}`,
    ]);
    matches = nodes.filter((node) => expected.has(node['resource-id']) || node['content-desc'] === selector.testID);
  } else if (selector.resourceId) {
    matches = nodes.filter((node) => node['resource-id'] === selector.resourceId);
  } else if (selector.contentDescription) {
    matches = nodes.filter((node) => node['content-desc'] === selector.contentDescription);
  } else if (selector.text) {
    if (!allowTextActions) throw new Error('text selectors require --allow-text-actions');
    matches = nodes.filter((node) => node.text === selector.text);
  } else {
    throw new Error('selector must use testID, resourceId, contentDescription, or an explicitly enabled exact text');
  }
  const occurrence = Number(selector.occurrence ?? 0);
  if (!Number.isInteger(occurrence) || occurrence < 0) throw new Error('selector occurrence must be a non-negative integer');
  if (!matches[occurrence]) throw new Error(`selector matched ${matches.length} nodes; occurrence ${occurrence} is unavailable`);
  return matches[occurrence];
}

export function actionSafety(action, node = null) {
  const supported = new Set(['capture', 'wait', 'tap', 'swipe', 'back']);
  if (!action || !supported.has(action.type)) return { safe: false, reason: `unsupported action type: ${action?.type ?? 'missing'}` };
  if (action.type === 'wait') {
    const ms = Number(action.ms ?? 500);
    if (!Number.isFinite(ms) || ms < 0 || ms > 5000) return { safe: false, reason: 'wait must be from 0 to 5000 ms' };
  }
  if (action.type === 'swipe' && !['up', 'down', 'left', 'right'].includes(action.direction)) {
    return { safe: false, reason: 'swipe direction must be up, down, left, or right' };
  }
  if (action.type === 'swipe') {
    const durationMs = Number(action.durationMs ?? 350);
    if (!Number.isFinite(durationMs) || durationMs < 100 || durationMs > 1200) {
      return { safe: false, reason: 'swipe duration must be from 100 to 1200 ms' };
    }
  }
  if (action.type === 'tap') {
    if (!node?.bounds) return { safe: false, reason: 'tap target has no deterministic bounds' };
    if (node.enabled === 'false') return { safe: false, reason: 'tap target is disabled' };
    const copy = [node.text, node['content-desc'], node['resource-id']].filter(Boolean).join(' ');
    const blocked = BLOCKED_ACTION_COPY.find((pattern) => pattern.test(copy));
    if (blocked) return { safe: false, reason: `tap target matches protected mutation copy: ${copy}` };
  }
  return { safe: true, reason: null };
}

export function tapPoint(node) {
  if (!node?.bounds) throw new Error('node has no bounds');
  return {
    x: Math.floor((node.bounds.left + node.bounds.right) / 2),
    y: Math.floor((node.bounds.top + node.bounds.bottom) / 2),
  };
}

export function swipePoints(direction, width, height) {
  const xMid = Math.floor(width * 0.5);
  const yMid = Math.floor(height * 0.5);
  const left = Math.floor(width * 0.2);
  const right = Math.floor(width * 0.8);
  const top = Math.floor(height * 0.25);
  const bottom = Math.floor(height * 0.75);
  if (direction === 'up') return [xMid, bottom, xMid, top];
  if (direction === 'down') return [xMid, top, xMid, bottom];
  if (direction === 'left') return [right, yMid, left, yMid];
  if (direction === 'right') return [left, yMid, right, yMid];
  throw new Error(`unsupported swipe direction: ${direction}`);
}

export function sanitizeSegment(value) {
  return String(value || 'capture').trim().replace(/[^a-zA-Z0-9._-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 80) || 'capture';
}

export function sha256(data) {
  return createHash('sha256').update(data).digest('hex');
}

export function parseMeminfo(text) {
  const total = String(text).match(/TOTAL PSS:\s*(\d+)\s+TOTAL RSS:\s*(\d+)\s+TOTAL SWAP PSS:\s*(\d+)/);
  return {
    totalPssKb: total ? Number(total[1]) : null,
    totalRssKb: total ? Number(total[2]) : null,
    totalSwapPssKb: total ? Number(total[3]) : null,
    viewCount: Number(String(text).match(/Views:\s*(\d+)/)?.[1] ?? 0) || null,
    activityCount: Number(String(text).match(/Activities:\s*(\d+)/)?.[1] ?? 0) || null,
    webViewCount: Number(String(text).match(/WebViews:\s*(\d+)/)?.[1] ?? 0) || null,
  };
}

export function summarizeLogcat(text) {
  const lines = String(text).split(/\r?\n/).filter(Boolean);
  const matching = (pattern) => lines.filter((line) => pattern.test(line));
  const invalidImageLines = matching(/ProgressiveDecoder: unknown image format/i);
  const invalidImageUrls = invalidImageLines
    .map((line) => line.match(/\buri:\s*([^,}\s]+)/i)?.[1] ?? null)
    .filter(Boolean);
  const contentionLines = matching(/Long monitor contention/i);
  const severeContentionLines = contentionLines.filter((line) => {
    const duration = line.match(/\bfor\s+(\d+(?:\.\d+)?)(ms|s)\b/i);
    if (!duration) return false;
    return duration[2].toLowerCase() === 's' ? Number(duration[1]) >= 1 : Number(duration[1]) >= 1000;
  });
  return {
    fatalLines: matching(/FATAL EXCEPTION|AndroidRuntime:\s+FATAL|ANR in |SIG(?:ABRT|SEGV)|OutOfMemory/i),
    invalidImageLines,
    invalidImageUrls: [...new Set(invalidImageUrls)],
    imageRoundingWarningCount: matching(/WrappingUtils: Don't know how to round that drawable/i).length,
    ttsErrorLines: matching(/TextToSpeech:.*(?:error|failed|timeout)/i),
    severeContentionLines,
  };
}
